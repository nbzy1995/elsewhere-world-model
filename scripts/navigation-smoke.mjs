import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';

const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const checks=[],errors=[];
page.on('pageerror',error=>errors.push(error.message));
const state=()=>page.evaluate(()=>JSON.parse(window.render_game_to_text()));
try{
  await page.goto('http://127.0.0.1:5179/scripts/navigation-smoke.html');
  await page.waitForFunction(()=>window.navigationReady);
  await page.locator('[data-nav="time"]').click();
  assert.equal((await state()).draftYear,2026);
  await page.locator('[data-time-preset="2126"]').click();
  assert.equal(await page.locator('[data-time-era]').textContent(),'Imagined future');
  await page.screenshot({path:'artifacts/navigation-time.png'});
  await page.locator('.world-time-submit').click();
  await page.waitForFunction(()=>!navigation.getState().dialog);
  assert.equal((await state()).world.year,2126);
  assert.equal((await state()).world.place,'New York');
  checks.push('separate time control calls onTime with year and leaves place unchanged');
  await page.locator('[data-nav="time"]').click();
  await page.locator('#worldTimeYear').fill('-500');
  assert.equal(await page.locator('[data-time-era]').textContent(),'Historical reconstruction');
  await page.locator('.world-time-submit').click();
  await page.waitForFunction(()=>!navigation.getState().dialog);
  assert.equal((await state()).world.year,-500);
  await page.locator('[data-nav="characters"]').click();
  assert.equal(await page.locator('[data-character-id]').count(),3);
  assert.equal(await page.locator('[data-character-id="city"]').isDisabled(),true);
  await page.screenshot({path:'artifacts/navigation-characters.png'});
  await page.locator('[data-character-id="factory"]').click();
  await page.waitForFunction(()=>!navigation.getState().dialog);
  assert.equal((await state()).activeCharacter,'factory');
  assert.equal((await state()).world.place,'Robotics factory');
  await page.locator('[data-nav="characters"]').click();
  await page.locator('[data-character-id="city"]').click();
  await page.waitForFunction(()=>!navigation.getState().dialog);
  assert.equal((await state()).world.year,-500);
  assert.equal((await state()).events.filter(e=>e.kind==='switch').at(-1).hasFrame,true);
  checks.push('character switch preserves the previous character world/year/frame and restores it');
  await page.evaluate(()=>window.callbackMode='pending');
  await page.locator('[data-nav="time"]').click();
  await page.locator('[data-time-preset="2126"]').click();
  await page.locator('.world-time-submit').click();
  assert.equal((await state()).pending,'time');
  assert.equal(await page.locator('#worldTimeYear').isDisabled(),true);
  await page.keyboard.press('Escape');
  await page.evaluate(()=>window.pendingResolver());
  await page.waitForTimeout(50);
  assert.equal((await state()).dialog,null);
  assert.equal((await state()).world.year,-500);
  checks.push('Escape aborts pending time change and stale completion cannot update UI');
  await page.evaluate(()=>window.callbackMode='error');
  await page.locator('[data-nav="time"]').click();
  await page.locator('.world-time-submit').click();
  await page.waitForFunction(()=>navigation.getState().feedback.includes('unavailable'));
  assert.equal((await state()).dialog,'time');
  assert.equal(await page.locator('#worldTimeYear').isDisabled(),false);
  await page.keyboard.press('Escape');
  await page.evaluate(()=>window.callbackMode='success');
  await page.locator('[data-nav="characters"]').click();
  await page.keyboard.press('Escape');
  assert.equal((await state()).dialog,null);
  checks.push('failed callback shows retryable error; Escape closes both dialogs');
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-nav="characters"]').click();
  const bounds=await page.locator('#worldCharactersDialog').boundingBox();
  assert.ok(bounds.x>=0&&bounds.x+bounds.width<=390);
  await page.screenshot({path:'artifacts/navigation-mobile.png'});
  checks.push('character cards fit a narrow viewport');
  assert.deepEqual(errors,[]);
  await writeFile('artifacts/navigation-report.json',JSON.stringify({result:'pass',checks,errors,state:await state()},null,2));
  console.log(JSON.stringify({result:'pass',checks,errors},null,2));
}finally{await browser.close();}
